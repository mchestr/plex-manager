/**
 * Reads each action's JSDoc summary from its source, for the MCP tool
 * descriptions. `npm run mcp:docs` writes `action-docs.generated.ts` from it,
 * because the standalone server has no source to read; a unit test fails when
 * that file is stale.
 *
 * The summary is the comment's first paragraph, with plan citations such as
 * `(P11.5, BP-30)` removed, since they mean nothing to a caller.
 *
 * @module lib/mcp/action-docs
 */

const EXPORT_PATTERN = /(?:\/\*\*((?:(?!\*\/)[\s\S])*)\*\/\s*)?export const (\w+)\s*=/g
const CITATION = /(?:P\d+\.\d+[a-z]?|[A-Z]{2,}-\d+[a-z]?|design [\d.]+|ui-design-system [\d.]+|FR-\d+)/
const CITATIONS = new RegExp(String.raw`\s*\((?:${CITATION.source})(?:,\s*(?:${CITATION.source}))*\)`, "g")

/** The comment's first paragraph as one line, citations removed. */
function summary(comment: string): string {
  const lines = comment.split("\n").map((line) => line.replace(/^\s*\*\s?/, "").trimEnd())
  const paragraph: string[] = []
  for (const line of lines) {
    if (line.trim() === "") {
      if (paragraph.length > 0) break
      continue
    }
    if (line.trim().startsWith("@")) break
    paragraph.push(line.trim())
  }
  // An inline tag such as `@public P8.8's playground shows it.` ends the summary
  const text = paragraph.join(" ").replace(/\s@\w+[\s\S]*$/, "")
  return text.replace(CITATIONS, "").replace(/\s+/g, " ").trim()
}

/** `{ exportName: summary }` for every documented `export const` in `source`. */
export function extractActionDocs(source: string): Record<string, string> {
  const docs: Record<string, string> = {}
  for (const match of source.matchAll(EXPORT_PATTERN)) {
    const text = match[1] ? summary(match[1]) : ""
    if (text) docs[match[2]] = text
  }
  return docs
}

/** The generated module's text for `docs`, sorted by name. */
export function renderActionDocs(docs: Record<string, string>): string {
  const entries = Object.keys(docs)
    .sort()
    .map((name) => `  ${name}: ${JSON.stringify(docs[name])},`)
  return [
    "// Generated by `npm run mcp:docs` from the actions' JSDoc (lib/mcp/action-docs.ts). Do not edit.",
    "",
    "export const ACTION_DOCS: Readonly<Record<string, string>> = {",
    ...entries,
    "}",
    "",
  ].join("\n")
}
