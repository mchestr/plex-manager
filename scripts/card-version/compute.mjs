/**
 * Computes `CARD_VERSION` (plan step P2.14, design 6.4) from the installed
 * packages and the committed card fonts:
 *
 *   rewind-cards@<n>+og@<x.y.z>+satori@<x.y.z>+fonts@<sha1-12>
 *
 * - `n` is `CARD_RENDERER_VERSION` in `lib/rewind/cards/version.ts`, bumped
 *   by hand when a card component or `CARD_SLACK` changes the pixels.
 * - The `@vercel/og` version comes from the package.json Next bundles it with.
 * - Satori is bundled without a package.json, so its version is read from the
 *   `satori@x.y.z` strings in `@vercel/og`'s Node build. Every match must
 *   agree, and none at all is an error: a Next upgrade must not silently
 *   produce a version without Satori's.
 * - `fonts` is the first 12 hex digits of a SHA-1 over every card font file
 *   (name, a NUL, then the bytes), in file-name order.
 */

import { createHash } from 'node:crypto'
import { readdirSync, readFileSync } from 'node:fs'
import { join } from 'node:path'

/** @internal */
export const CARD_VERSION_PATTERN = /^rewind-cards@\d+\+og@\d+\.\d+\.\d+\+satori@\d+\.\d+\.\d+\+fonts@[0-9a-f]{12}$/

const OG_DIR = ['node_modules', 'next', 'dist', 'compiled', '@vercel', 'og']
const FONT_DIR = ['lib', 'rewind', 'cards', 'fonts']
export const GENERATED = ['lib', 'rewind', 'cards', 'card-version.generated.ts']

function rendererVersion(root) {
  const source = readFileSync(join(root, 'lib', 'rewind', 'cards', 'version.ts'), 'utf8')
  const match = /export const CARD_RENDERER_VERSION = (\d+)\b/.exec(source)
  if (!match) throw new Error('lib/rewind/cards/version.ts does not export CARD_RENDERER_VERSION = <n>')
  return Number(match[1])
}

function ogVersion(root) {
  return JSON.parse(readFileSync(join(root, ...OG_DIR, 'package.json'), 'utf8')).version
}

/** @internal */
export function satoriVersion(root) {
  const bundle = readFileSync(join(root, ...OG_DIR, 'index.node.js'), 'utf8')
  const versions = new Set([...bundle.matchAll(/satori@(\d+\.\d+\.\d+)/g)].map((m) => m[1]))
  if (versions.size !== 1) {
    throw new Error(
      versions.size === 0
        ? 'No satori@x.y.z in next/dist/compiled/@vercel/og/index.node.js: find where this Next version records Satori and update scripts/card-version/compute.mjs'
        : `Conflicting Satori versions in @vercel/og: ${[...versions].join(', ')}`,
    )
  }
  return [...versions][0]
}

function fontsHash(root) {
  const dir = join(root, ...FONT_DIR)
  const hash = createHash('sha1')
  for (const file of readdirSync(dir).filter((f) => f.endsWith('.ttf')).sort()) {
    hash.update(file).update('\0').update(readFileSync(join(dir, file)))
  }
  return hash.digest('hex').slice(0, 12)
}

export function computeCardVersion(root) {
  return `rewind-cards@${rendererVersion(root)}+og@${ogVersion(root)}+satori@${satoriVersion(root)}+fonts@${fontsHash(root)}`
}

export function generatedSource(version) {
  return [
    '// Generated by scripts/write-card-version.mjs from the installed next/og and the card fonts.',
    '// Do not edit: run `npm run rewind:card-version` after upgrading Next or rebuilding the fonts.',
    `export const CARD_VERSION = ${JSON.stringify(version)}`,
    '',
  ].join('\n')
}
