/**
 * Writes the environment reference from `envSchema` (P11.24, GAP-18):
 * `docs/environment.md`, one table per group, and the part of `example.env`
 * between `# BEGIN GENERATED` and `# END GENERATED`.
 *
 *   npm run env:docs              # rewrite both files
 *   npm run env:docs -- --check   # exit 1 when either is out of date (CI)
 *
 * Each variable's description, group, default and requirement come from its
 * Zod metadata in `lib/env.ts`, so the reference changes only there.
 *
 * @module
 */

import { readFileSync, writeFileSync } from "node:fs"
import path from "node:path"

import type { z } from "zod"

import { ENV_GROUPS, envSchema, type EnvDoc } from "@/lib/env"

export interface EnvEntry extends EnvDoc {
  name: string
  description: string
}

type Group = EnvDoc["group"]

export const DOC_PATH = "docs/environment.md"
export const EXAMPLE_PATH = "example.env"
const BEGIN = "# BEGIN GENERATED by `npm run env:docs` from lib/env.ts; edit the descriptions there"
const END = "# END GENERATED"
const WIDTH = 79

/** The schema's variables with their metadata, in schema order. */
export function envEntries(shape: Record<string, z.ZodType> = envSchema.shape): EnvEntry[] {
  return Object.entries(shape).map(([name, field]) => {
    const meta = field.meta() as (EnvDoc & { description?: string }) | undefined
    if (!meta?.group || !meta.description) throw new Error(`${name} has no group or description in lib/env.ts`)
    return { ...meta, name, description: meta.description }
  })
}

function byGroup(entries: readonly EnvEntry[]): [Group, EnvEntry[]][] {
  return ENV_GROUPS.map((group): [Group, EnvEntry[]] => [group, entries.filter((entry) => entry.group === group)]).filter(
    ([, members]) => members.length > 0
  )
}

function requirement(entry: EnvEntry): string {
  if (entry.requiredInProduction) return "yes (boot check)"
  return entry.required ? "yes" : ""
}

const cell = (value: string) => value.replace(/\|/g, "\\|")

/** `docs/environment.md`. */
export function renderMarkdown(entries: readonly EnvEntry[]): string {
  const lines = [
    "# Environment variables",
    "",
    "<!-- Generated by `npm run env:docs` from lib/env.ts. Edit the descriptions there; CI fails when this file is out of date. -->",
    "",
    "Every variable the app reads. `example.env` lists the same variables with development values.",
    "",
    '- **Required in production**: "yes (boot check)" means a production server logs `env.invalid` with the',
    "  variable's name and exits with code 1 when it is missing (`checkProductionEnv` in `lib/env.ts`). It",
    "  also exits when `NEXTAUTH_SECRET` is short or a known placeholder, when either URL is not https",
    "  (unless `ALLOW_INSECURE_HTTP=true`), and when `SETUP_TOKEN` is shorter than 16 characters.",
    '  "yes" means the app cannot run without it, though the boot check does not test it.',
    "- **Docker Compose** also reads `POSTGRES_PASSWORD` and `REDIS_PASSWORD`, which it passes to Postgres and",
    "  Redis; see [deployment](deployment.md). The app itself never reads them.",
    "- **`DEV_*`** variables prefill the setup wizard in development only; `example.env` lists them.",
    "- **Test only** variables are for the test suites and must never be set in production.",
    "",
    "See [deployment](deployment.md) for an install and [domain move](domain-move.md) for changing the URL.",
  ]
  for (const [group, members] of byGroup(entries)) {
    lines.push("", `## ${group}`, "", "| Variable | Required in production | Default | Description |", "|---|---|---|---|")
    for (const entry of members) {
      const fallback = entry.default === undefined ? "" : `\`${entry.default}\``
      lines.push(`| \`${entry.name}\` | ${requirement(entry)} | ${cell(fallback)} | ${cell(entry.description)} |`)
    }
  }
  return `${lines.join("\n")}\n`
}

function wrap(text: string): string[] {
  const lines: string[] = []
  let line = "#"
  for (const word of text.split(/\s+/)) {
    if (line.length + 1 + word.length > WIDTH && line !== "#") {
      lines.push(line)
      line = "#"
    }
    line += ` ${word}`
  }
  lines.push(line)
  return lines
}

function groupHeading(group: Group): string[] {
  const rule = group === "Test only" ? "=".repeat(WIDTH - 2) : "-".repeat(WIDTH - 2)
  const title = group === "Test only" ? "TEST ONLY - NEVER IN PRODUCTION" : group
  return [`# ${rule}`, `# ${title}`, `# ${rule}`]
}

/** The lines `example.env` holds between its markers, markers included. */
export function renderExampleBlock(entries: readonly EnvEntry[]): string {
  const lines = [BEGIN]
  for (const [group, members] of byGroup(entries)) {
    lines.push("", ...groupHeading(group))
    for (const entry of members) {
      lines.push("", ...wrap(entry.description))
      if (entry.requiredInProduction) lines.push("# Required in production: the server refuses to start without it.")
      if (entry.default !== undefined) lines.push(`# Default: ${entry.default}`)
      const value = entry.example ?? ""
      lines.push(entry.example !== undefined || entry.required ? `${entry.name}="${value}"` : `# ${entry.name}=""`)
    }
  }
  lines.push("", END)
  return lines.join("\n")
}

/** `current` with the generated block replaced. Throws when a marker is missing. */
export function replaceExampleBlock(current: string, block: string): string {
  const start = current.indexOf("# BEGIN GENERATED")
  const endMarker = current.indexOf(END)
  if (start === -1 || endMarker === -1 || endMarker < start) {
    throw new Error(`${EXAMPLE_PATH} needs a "# BEGIN GENERATED" line followed by a "${END}" line`)
  }
  return current.slice(0, start) + block + current.slice(endMarker + END.length)
}

export interface GenDeps {
  readFile: (relative: string) => string
  writeFile: (relative: string, text: string) => void
  log: (line: string) => void
}

/** Writes both outputs, or with `--check` reports the stale ones; returns the exit code. */
export function main(argv: readonly string[], deps: GenDeps, entries: readonly EnvEntry[] = envEntries()): number {
  const check = argv.includes("--check")
  const outputs: Record<string, string> = {
    [DOC_PATH]: renderMarkdown(entries),
    [EXAMPLE_PATH]: replaceExampleBlock(deps.readFile(EXAMPLE_PATH), renderExampleBlock(entries)),
  }
  const stale = Object.keys(outputs).filter((file) => {
    try {
      return deps.readFile(file) !== outputs[file]
    } catch {
      return true
    }
  })
  if (check) {
    for (const file of stale) deps.log(`${file} is out of date with lib/env.ts: run npm run env:docs`)
    return stale.length > 0 ? 1 : 0
  }
  for (const file of stale) {
    deps.writeFile(file, outputs[file])
    deps.log(`wrote ${file}`)
  }
  return 0
}

if (require.main === module) {
  const root = path.resolve(__dirname, "..")
  process.exitCode = main(process.argv.slice(2), {
    readFile: (relative) => readFileSync(path.join(root, relative), "utf8"),
    writeFile: (relative, text) => writeFileSync(path.join(root, relative), text),
    log: (line) => console.log(line),
  })
}
