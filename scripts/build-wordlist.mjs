#!/usr/bin/env node
/**
 * Regenerates `lib/wrapped/copy/wordlist.ts`, the common-word list that
 * grounding rule 4 checks sentence-initial words against (design 8.4).
 *
 * Source: the 10,000 most frequent English 1-grams of the Google Books Ngram
 * Corpus (v3, books from 2010-2019), cleaned by orgtre/google-books-ngram-frequency
 * and licensed CC BY 3.0 (attribution, not share-alike). The file is pinned
 * by commit and checked against its sha256.
 *
 * Capitalised entries (months, places, nations, "God") are left out, except
 * "I": they are proper nouns, which copy must set as tokens. The rest are
 * lower-cased.
 *
 * Usage: node scripts/build-wordlist.mjs [path/to/1grams_english.csv]
 * Without a path the pinned file is downloaded.
 */

import { createHash } from "node:crypto"
import { readFileSync, writeFileSync } from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"

const COMMIT = "e20471c15a758be3362b16d07870b34df4f7ccc3"
const SOURCE_URL = `https://raw.githubusercontent.com/orgtre/google-books-ngram-frequency/${COMMIT}/ngrams/1grams_english.csv`
const SHA256 = "f7f63aa08f0bb2f7f654cddff3a7ced4968b27887b2c0e7cd4b4d108221e197d"
const OUT = path.join(path.dirname(fileURLToPath(import.meta.url)), "..", "lib", "wrapped", "copy", "wordlist.ts")

async function source(file) {
  if (file) return readFileSync(file)
  const res = await fetch(SOURCE_URL)
  if (!res.ok) throw new Error(`Download failed: ${res.status}`)
  return Buffer.from(await res.arrayBuffer())
}

const csv = await source(process.argv[2])
const sha = createHash("sha256").update(csv).digest("hex")
if (sha !== SHA256) throw new Error(`sha256 mismatch: ${sha}`)

const words = csv
  .toString("utf8")
  .split("\n")
  .slice(1)
  .map((line) => line.split(",")[0].trim())
  .filter((word) => word && (word === "I" || word === word.toLowerCase()))
  .map((word) => word.toLowerCase())
const unique = [...new Set(words)]

const lines = []
for (let i = 0; i < unique.length; i += 16) lines.push(`  "${unique.slice(i, i + 16).join(" ")}",`)

writeFileSync(
  OUT,
  `/**
 * The common English words a sentence may start with (grounding rule 4,
 * design 8.4): ${unique.length} lower-cased words, the 10,000 most frequent
 * 1-grams of the Google Books Ngram Corpus minus the capitalised ones.
 *
 * Generated by \`scripts/build-wordlist.mjs\`; do not edit. Source:
 * github.com/orgtre/google-books-ngram-frequency at ${COMMIT.slice(0, 12)},
 * \`ngrams/1grams_english.csv\` (sha256 ${SHA256.slice(0, 16)}...), from the
 * Google Books Ngram Corpus v3. Licence: Creative Commons Attribution 3.0
 * Unported (https://creativecommons.org/licenses/by/3.0/).
 *
 * @module lib/wrapped/copy/wordlist
 */

const CHUNKS = [
${lines.join("\n")}
]

export const COMMON_WORDS: ReadonlySet<string> = new Set(CHUNKS.join(" ").split(" "))
`
)
console.log(`Wrote ${unique.length} words to ${path.relative(process.cwd(), OUT)}`)
